// Текущий язык
window.currentLang = localStorage.getItem('key_lang') || 'ru';
window.KEY_TRANSLATIONS = KEY_TRANSLATIONS;

function applyLanguage(lang) {
    window.currentLang = lang;
    localStorage.setItem('key_lang', lang);
    const t = KEY_TRANSLATIONS[lang];
    if (!t) return;

    // Переводим все элементы с data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key] !== undefined) {
            el.innerHTML = t[key];
        }
    });

    // Переводим title страницы
    const titleEl = document.querySelector('[data-i18n-title]');
    if (titleEl) {
        const titleKey = titleEl.getAttribute('data-i18n-title');
        if (t[titleKey]) document.title = t[titleKey];
    }

    // Переводим placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key] !== undefined) {
            el.placeholder = t[key];
        }
    });


    // Обновляем бегущие строки
    const tickerMap = {
        'ticker': 'ticker_index',
        'tickerLabel': 'ticker_label',
        'tickerPR': 'ticker_pr',
        'tickerBook': 'ticker_booking',
        'tickerLegal': 'ticker_legal',
    };
    Object.entries(tickerMap).forEach(([id, key]) => {
        const el = document.getElementById(id);
        if (!el || !t[key]) return;
        const text = t[key];
        el.innerHTML = `<span style="display:inline-block;white-space:nowrap;padding:0 40px;font-size:0.65rem;font-weight:900;letter-spacing:3px;text-transform:uppercase;color:rgba(255,255,255,0.28);">${text}</span><span style="display:inline-block;white-space:nowrap;padding:0 40px;font-size:0.65rem;font-weight:900;letter-spacing:3px;text-transform:uppercase;color:rgba(255,255,255,0.28);">${text}</span>`;
        // Заменяем ✦ на лаймовые
        el.querySelectorAll('span').forEach(s => {
            s.innerHTML = s.innerHTML.replace(/✦/g, '<span style="color:#D3FF33;font-weight:900;">✦</span>');
        });
    });

    // Обновляем переключатели — inline стили для надёжности
    document.querySelectorAll('.lang-btn').forEach(btn => {
        const isActive = btn.getAttribute('data-lang') === lang;
        btn.classList.toggle('active', isActive);
        btn.style.color = isActive ? '#D3FF33' : 'rgba(255,255,255,0.35)';
        btn.style.background = isActive ? 'rgba(211,255,51,0.08)' : 'none';
    });
}

function initLanguage() {
    applyLanguage(window.currentLang);
}

window.initLanguage = initLanguage;
window.applyLanguage = applyLanguage;

// Применяем active класс СРАЗУ (до DOMContentLoaded) чтобы не было мигания
(function() {
    var lang = localStorage.getItem('key_lang') || 'ru';
    // Ставим active на кнопки как только DOM доступен
    function setActive() {
        document.querySelectorAll('.lang-btn').forEach(function(btn) {
            btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
        });
    }
    // Полный перевод после загрузки
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function() {
            setActive();
            applyLanguage(lang);
        });
    } else {
        setActive();
        applyLanguage(lang);
    }
})();
